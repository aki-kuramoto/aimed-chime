//go:build darwin

package sound

// macOS backend: devices are listed and played through ffmpeg's audiotoolbox output,
// channel counts and names come from CoreAudio, and speech is rendered with say.

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func ffmpegPath(cfg Config) (string, error) {
	if cfg.FFmpeg != "" {
		return cfg.FFmpeg, nil
	}
	if path, err := exec.LookPath("ffmpeg"); err == nil {
		return path, nil
	}
	// MCP servers are sometimes started with a minimal PATH.
	for _, path := range []string{"/opt/homebrew/bin/ffmpeg", "/usr/local/bin/ffmpeg"} {
		if _, err := os.Stat(path); err == nil {
			return path, nil
		}
	}
	return "", errors.New("ffmpeg not found (install it, or set ffmpeg in the config file)")
}

// listDevices asks ffmpeg for the audiotoolbox device list and joins it with CoreAudio's device info by UID.
func listDevices(ctx context.Context, cfg Config) ([]Device, error) {
	ff, err := ffmpegPath(cfg)
	if err != nil {
		return nil, err
	}
	out, err := exec.CommandContext(ctx, ff, "-hide_banner",
		"-f", "lavfi", "-i", "anullsrc", "-t", "0.01",
		"-f", "audiotoolbox", "-list_devices", "true", "-").CombinedOutput()
	devs := ParseDevices(string(out))
	if len(devs) == 0 {
		if err != nil {
			return nil, fmt.Errorf("ffmpeg -list_devices failed: %v\n%s", err, strings.TrimSpace(string(out)))
		}
		return nil, errors.New("ffmpeg listed no audiotoolbox devices")
	}
	ca := coreAudioDevices()
	for i := range devs {
		if info, ok := ca[devs[i].UID]; ok {
			if info.Name != "" {
				devs[i].Name = info.Name
			}
			devs[i].Inputs, devs[i].Outputs, devs[i].Known = info.Inputs, info.Outputs, true
		}
	}
	return devs, nil
}

// Lines look like "[AudioToolbox @ 0x...] [1]   (null), SomeDeviceUID".
var deviceLine = regexp.MustCompile(`\[AudioToolbox @ [^\]]*\]\s+\[(\d+)\]\s+(.*)$`)

// ParseDevices picks the device lines out of ffmpeg's output. Name and UID are split at the last ", ".
func ParseDevices(out string) []Device {
	var devs []Device
	for _, line := range strings.Split(out, "\n") {
		m := deviceLine.FindStringSubmatch(strings.TrimRight(line, "\r"))
		if m == nil {
			continue
		}
		idx, _ := strconv.Atoi(m[1])
		rest := strings.TrimSpace(m[2])
		d := Device{Index: idx, Name: rest}
		if i := strings.LastIndex(rest, ", "); i >= 0 {
			d.Name, d.UID = strings.TrimSpace(rest[:i]), strings.TrimSpace(rest[i+2:])
		}
		devs = append(devs, d)
	}
	return devs
}

// playChime plays the chime once: 880 -> 660 -> 990 Hz sine tones generated by ffmpeg.
func playChime(ctx context.Context, cfg Config, d Device, volume float64) error {
	ff, err := ffmpegPath(cfg)
	if err != nil {
		return err
	}
	filter := fmt.Sprintf("[0][1][2]concat=n=3:v=0:a=1,volume=%g,aformat=channel_layouts=stereo", volume)
	return run(ctx, ff, "-hide_banner", "-loglevel", "error",
		"-f", "lavfi", "-i", "sine=frequency=880:duration=0.25",
		"-f", "lavfi", "-i", "sine=frequency=660:duration=0.25",
		"-f", "lavfi", "-i", "sine=frequency=990:duration=0.5",
		"-filter_complex", filter,
		"-f", "audiotoolbox", "-audio_device_index", strconv.Itoa(d.Index), "-")
}

// renderSpeech renders the text to an AIFF file with say, because say itself has no gain option.
// The text goes through stdin so that its length is not limited by the command-line size.
// The caller removes the file. voice is what was used, for reporting.
func renderSpeech(ctx context.Context, cfg Config, text string) (path, voice string, err error) {
	voice = DefaultVoice
	var args []string
	if cfg.Voice != "" {
		voice = cfg.Voice
		// say silently falls back to the default voice for an unknown name, so check it first.
		if err := checkVoice(ctx, cfg.Voice); err != nil {
			return "", voice, err
		}
		args = append(args, "-v", cfg.Voice)
	}
	tmp, err := os.CreateTemp("", "aimed-chime-*.aiff")
	if err != nil {
		return "", voice, err
	}
	tmp.Close()
	cmd := exec.CommandContext(ctx, "say", append(args, "-o", tmp.Name(), "-f", "-")...)
	cmd.Stdin = strings.NewReader(text)
	if out, err := cmd.CombinedOutput(); err != nil {
		os.Remove(tmp.Name())
		return "", voice, fmt.Errorf("say failed: %v\n%s", err, strings.TrimSpace(string(out)))
	}
	return tmp.Name(), voice, nil
}

// playSpeech plays a rendered file through ffmpeg.
// 1.5 seconds of silence is appended, because the end of the speech was cut off without it in the environments tested.
func playSpeech(ctx context.Context, cfg Config, d Device, path string, volume float64) error {
	ff, err := ffmpegPath(cfg)
	if err != nil {
		return err
	}
	af := fmt.Sprintf("volume=%g,apad=pad_dur=1.5,aformat=channel_layouts=stereo", volume)
	return run(ctx, ff, "-hide_banner", "-loglevel", "error", "-i", path,
		"-af", af, "-f", "audiotoolbox", "-audio_device_index", strconv.Itoa(d.Index), "-")
}

// Lines of `say -v ?` look like "Name (Language (Region))   ja_JP    # sample text"; names may contain spaces.
var voiceLine = regexp.MustCompile(`^(.*\S)\s+([a-z]{2,3}_[A-Za-z0-9]+)\s+#`)

// ParseVoices returns the voice names listed by `say -v ?`.
func ParseVoices(out string) []string {
	var names []string
	for _, line := range strings.Split(out, "\n") {
		if m := voiceLine.FindStringSubmatch(line); m != nil {
			names = append(names, m[1])
		}
	}
	return names
}

func checkVoice(ctx context.Context, voice string) error {
	out, err := exec.CommandContext(ctx, "say", "-v", "?").Output()
	if err != nil {
		return fmt.Errorf("say -v ? failed: %v", err)
	}
	for _, name := range ParseVoices(string(out)) {
		if name == voice {
			return nil
		}
	}
	return fmt.Errorf("voice %q is not installed (see: say -v '?')", voice)
}

func run(ctx context.Context, name string, args ...string) error {
	out, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s failed: %v\n%s", filepath.Base(name), err, strings.TrimSpace(string(out)))
	}
	return nil
}
